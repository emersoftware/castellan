/** Speaker notes for presenter.html, generated from contenido-v2.json (the script's source of truth).
 *  Fails if the scenes in index.html and the script disagree in ids or order, or if the timing
 *  no longer adds up to the 23 minutes of content.
 *    node build-notes.mjs */
import { readFile, writeFile } from 'node:fs/promises';
const here = new URL('./', import.meta.url);
const content = JSON.parse(await readFile(new URL('contenido-v2.json', here), 'utf8'));
const html = await readFile(new URL('index.html', here), 'utf8');
const sections = [...html.matchAll(/<section class="scene[^"]*" id="([^"]+)"[^>]*data-steps="(\d+)"[^>]*data-cues="([^"]*)"/g)]
  .map(([, id, steps, cues]) => ({ id, steps: Number(steps), cues: cues.split('|') }));
const ids = content.map(s => s.id), htmlIds = sections.map(s => s.id);
if (ids.join() !== htmlIds.join()) throw new Error(`Scene ids differ.\n  contenido-v2.json: ${ids.join(', ')}\n  index.html:        ${htmlIds.join(', ')}`);
for (const s of sections) if (s.cues.length !== s.steps) throw new Error(`${s.id}: ${s.steps} steps but ${s.cues.length} cues`);
const total = content.reduce((sum, s) => sum + s.seconds, 0);
if (total !== 1380) console.warn(`Aviso: el contenido suma ${total} s, no 1380 s (23 min); falta reajustar tiempos tras reestructurar.`);
let start = 0;
const notes = content.map((s, i) => {
  const note = { n: i + 1, id: s.id, title: s.title, seconds: s.seconds, start, timing: s.timing, script: s.script, source: s.source, steps: sections[i].steps, cues: sections[i].cues };
  start += s.seconds;
  return note;
});
await writeFile(new URL('notes.js', here), `// Generated by build-notes.mjs from contenido-v2.json. Do not edit by hand.\nwindow.TALK_NOTES = ${JSON.stringify(notes, null, 1)};\n`);
console.log(`notes.js: ${notes.length} scenes, ${total / 60} min, ${sections.reduce((a, s) => a + s.steps, 0)} steps`);
